const rawAlert = (input: {
  id: string;
  code: AlertCode;
  status: AlertStatus;
  severity: AlertSeverity;
  entityType: EntityTypeValue;
  entityId: string;
  startedAt: string;
  resolvedAt: string | null;
  title: string;
  description: string;
  scenarioId: string | null;
  sequence: number;
}) => {
  const lastObservedAt = input.resolvedAt ?? ACTIVITY_WINDOW_END;
  return {
    id: input.id,
    code: input.code,
    status: input.status,
    severity: input.severity,
    sourceEntity: { entityType: input.entityType, entityId: input.entityId },
    startedAt: input.startedAt,
    lastObservedAt,
    ...(input.resolvedAt === null ? {} : { resolvedAt: input.resolvedAt }),
    durationMs: Date.parse(lastObservedAt) - Date.parse(input.startedAt),
    message: input.description,
    probableCause: 'Deterministic simulated activity fixture condition.',
    recommendedAction: 'Inspect the simulated record context; no device action is available.',
    metadata: {
      title: input.title,
      description: input.description,
      scenarioId: input.scenarioId,
      sequence: input.sequence,
      dataSource: DataSource.SIMULATED,
    },
  };
};

